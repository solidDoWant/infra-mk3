#!/usr/bin/env bash
# Regenerates the encrypted CiliumCIDRGroup that allows the VPN gateway to reach its
# WireGuard servers. Run it after a gluetun bump or a SERVER_COUNTRIES_<n> change: the
# gateway can only connect to servers in this list.
#
# The list holds every WireGuard server IPv4 that gluetun can pick for the provider and
# countries in the gateway secret (gluetun only uses the server list bundled in its
# image). It is padded with unused RFC 5737 documentation addresses to a fixed size and
# shuffled, so the encrypted file doesn't reveal how many real servers there are.
# Documentation addresses are never routed, so allowing egress to them is harmless.

set -euo pipefail

PAD_TO="${PAD_TO:-64}"

repo="$(git rev-parse --show-toplevel)"
gateway_dir="${repo}/cluster/gitops/networking/vpn/gateway"
secret_file="${gateway_dir}/vpn-credentials.sops.yaml"
out_file="${repo}/cluster/gitops/cilium/cilium/netpols/vpn-endpoints.cidrs.sops.yaml"

gluetun_tag="$(yq '.. | select(has("repository") and .repository == "ghcr.io/qdm12/gluetun") | .tag' \
    "${gateway_dir}/hr.yaml" | head -n 1 | cut -d@ -f1)"
if [[ ! "${gluetun_tag}" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "couldn't find the gluetun image tag in ${gateway_dir}/hr.yaml" >&2
    exit 1
fi

# Keep the decrypted secret in memory only.
secret="$(sops -d "${secret_file}")"
provider="$(yq '.stringData.VPN_SERVICE_PROVIDER' <<<"${secret}")"
countries="$(yq -o json -I0 \
    '[.stringData | to_entries[] | select(.key | test("^SERVER_COUNTRIES_")) | .value | split(",")[] | trim | downcase]' \
    <<<"${secret}")"
unset secret

servers_json="$(curl -fsSL "https://raw.githubusercontent.com/qdm12/gluetun/${gluetun_tag}/internal/storage/servers.json")"
mapfile -t ips < <(jq -r --arg p "${provider}" --argjson c "${countries}" '
    to_entries[]
    | select(.key | ascii_downcase == ($p | ascii_downcase))
    | .value.servers[]
    | select((.vpn // "wireguard") == "wireguard")
    | select((.country | ascii_downcase) as $x | $c | index($x))
    | .ips[]?
    | select(contains(":") | not)' <<<"${servers_json}" | sort -u)

if ((${#ips[@]} == 0)); then
    echo "no WireGuard servers matched; check the provider and countries in the secret" >&2
    exit 1
fi
if ((${#ips[@]} > PAD_TO)); then
    echo "${#ips[@]} servers matched, more than PAD_TO=${PAD_TO}; rerun with a larger PAD_TO" >&2
    exit 1
fi

mapfile -t padding < <(
    for net in 192.0.2 198.51.100 203.0.113; do
        for host in $(seq 1 254); do echo "${net}.${host}"; done
    done | shuf -n "$((PAD_TO - ${#ips[@]}))"
)

plaintext="$(
    cat <<EOF
# Generated by .taskfiles/vpn/generate-endpoints.sh (task vpn:generate-endpoints) from
# gluetun ${gluetun_tag}. Don't edit by hand. Holds the WireGuard servers the VPN gateway
# pods can pick, padded with unrouted documentation addresses so the size doesn't leak.
apiVersion: cilium.io/v2
kind: CiliumCIDRGroup
metadata:
  name: vpn-endpoints
  labels:
    external.netpols.home.arpa/egress.vpn-endpoints: "true"
spec:
  externalCIDRs:
EOF
    printf '%s\n' "${ips[@]}" "${padding[@]}" | shuf | sed 's|.*|    - &/32|'
)"

tmp_out="$(mktemp "${out_file}.XXXXXX")"
trap 'rm -f "${tmp_out}"' EXIT
sops encrypt --filename-override "${out_file}" /dev/stdin <<<"${plaintext}" >"${tmp_out}"
mv "${tmp_out}" "${out_file}"
trap - EXIT

echo "Wrote ${out_file} (gluetun ${gluetun_tag}, ${#ips[@]} servers padded to ${PAD_TO})"
