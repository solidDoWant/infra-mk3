#!/usr/bin/env bash
# Writes the CI PipelineRuns .tekton/pull-request.yaml and .tekton/push.yaml
# from scripts/ci/tekton-pipelinerun.yaml.tmpl, and the release PipelineRun
# .tekton/release.yaml from scripts/ci/tekton-release.yaml.tmpl. Part of
# `make generate`, so `make check-generate` fails when .tekton/ is stale.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

template=scripts/ci/tekton-pipelinerun.yaml.tmpl

# render NAME EVENT CEL: writes .tekton/NAME.yaml without the template's own
# header comment, and with the pull-request-only lines only for pull requests.
render() {
	{
		echo "# Generated by scripts/ci/tekton-generate.sh from $template. Do not edit."
		awk -v name="$1" -v event="$2" -v cel="$3" '
			function replace(text, from, to,   out, at) {
				out = ""
				while ((at = index(text, from)) > 0) {
					out = out substr(text, 1, at - 1) to
					text = substr(text, at + length(from))
				}
				return out text
			}
			/^apiVersion:/ { started = 1 }
			!started { next }
			/^#@pull_request \{$/ { inside = 1; next }
			/^#@pull_request \}$/ { inside = 0; next }
			inside && event != "pull_request" { next }
			{
				line = replace($0, "@NAME@", name)
				line = replace(line, "@EVENT@", event)
				print replace(line, "@CEL@", cel)
			}
		' "$template"
	} >".tekton/$1.yaml.tmp"
	mv ".tekton/$1.yaml.tmp" ".tekton/$1.yaml"
}

mkdir -p .tekton
render pull-request pull_request 'event == "pull_request" && target_branch == "master"'
render push push 'event == "push" && target_branch == "master"'

release_template=scripts/ci/tekton-release.yaml.tmpl
{
	echo "# Generated by scripts/ci/tekton-generate.sh from $release_template. Do not edit."
	awk '/^apiVersion:/ { started = 1 } started' "$release_template"
} >.tekton/release.yaml.tmp
mv .tekton/release.yaml.tmp .tekton/release.yaml
